/**
 * `twinmemory-cli doctor`: whether a project is set up for memory, one line per check, each with
 * how to fix it when it is not. Reads everything and changes nothing; the one request it makes is
 * the key's check, which is free.
 */

import { readFileSync } from "node:fs";
import { relative } from "node:path";

import * as env from "./env.js";
import * as project from "./project.js";
import { MINIMUMS } from "./scaffold.js";
import type { Console } from "./ui.js";
import { VERSION } from "./version.js";

const GENERATED = /Generated by `twinmemory-cli init langgraph[^`]*` \(twinmemory-cli ([^)]+)\)/;

function mark(console: Console, ok: boolean | undefined, what: string, fix = ""): boolean {
  console.line(`  ${ok === undefined ? "-" : ok ? "✓" : "✗"} ${what}`);
  if (ok === false && fix) console.line(`      ${fix}`);
  return ok !== false;
}

/** 0 when every check passes, 1 when any fails. */
export async function doctor(
  cwd: string,
  console: Console,
  check: env.Checker = env.check,
): Promise<number> {
  const root = project.findRoot(cwd);
  if (!root) {
    console.fail("no JavaScript project here; run it from your project.");
    return 1;
  }
  console.line(`twinmemory-cli ${VERSION} - checking ${root}`);
  const written = memoryFiles(root, console);
  const results = [written.length > 0, dependencies(root, console), versions(root, console)];
  const saves = written.some((path) =>
    /export async function remember\(|name: "memory_add"/.test(readFileSync(path, "utf8")),
  );
  results.push(await key(root, console, saves, check));
  console.line();
  const good = results.every(Boolean);
  console.line(good ? "All good." : "Fix what is marked ✗, then run doctor again.");
  return good ? 0 : 1;
}

function memoryFiles(root: string, console: Console): string[] {
  const found: string[] = [];
  for (const path of project.sources(root)) {
    const match = GENERATED.exec(readFileSync(path, "utf8").slice(0, 2000));
    if (match) {
      found.push(path);
      mark(console, true, `memory file ${relative(root, path)} (written by ${match[1]})`);
    }
  }
  if (!found.length)
    mark(console, false, "no memory file", "run `npx twinmemory-cli init langgraph`");
  return found;
}

function dependencies(root: string, console: Console): boolean {
  const missing = Object.keys(MINIMUMS).filter((name) => !project.declares(root, name));
  if (missing.length) {
    const add = project
      .installer(
        root,
        missing.map((n) => `'${n}@>=${MINIMUMS[n]}'`),
      )
      .command.join(" ");
    return mark(console, false, `not dependencies: ${missing.join(", ")}`, add);
  }
  return mark(console, true, `dependencies: ${Object.keys(MINIMUMS).join(", ")}`);
}

function versions(root: string, console: Console): boolean {
  let ok = true;
  for (const [name, minimum] of Object.entries(MINIMUMS)) {
    const version = project.installed(root, name);
    if (version === undefined)
      ok =
        mark(console, false, `${name} is not installed`, "install the project's dependencies") &&
        ok;
    else if (project.older(version, minimum))
      ok =
        mark(
          console,
          false,
          `${name} ${version} is older than ${minimum}`,
          `upgrade it to >=${minimum}`,
        ) && ok;
    else mark(console, true, `${name} ${version}`);
  }
  return ok;
}

async function key(
  root: string,
  console: Console,
  saves: boolean,
  check: env.Checker,
): Promise<boolean> {
  const { key, baseUrl } = env.resolveKey(root);
  const where = baseUrl ?? "the hosted service";
  if (!key)
    return mark(
      console,
      false,
      `no ${env.KEY}`,
      `put a key in .env as ${env.KEY}= (console, under API keys)`,
    );
  const keptOut =
    env.ignored(root) ||
    mark(console, false, ".env is not in .gitignore", "add .env to .gitignore");
  const checked = await check(key, baseUrl);
  if (!checked.ok)
    return mark(
      console,
      false,
      `key at ${where}: ${checked.detail}`,
      `check ${env.KEY} and ${env.BASE_URL}`,
    );
  if (saves && checked.writes === false) {
    return mark(
      console,
      false,
      `key at ${where} only reads, and the memory file saves: remember and memory_add will be refused`,
      "use a key that writes (console, under API keys)",
    );
  }
  return mark(console, true, `key at ${where}: ${checked.detail}`) && keptOut;
}
