pytest.importorskip("agents")

from agents.testing.model import (  # noqa: E402
    ScriptedModel,
    assistant_message,
    function_call,
)


@pytest.fixture
def created(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Any:
    """Make a project with a preset, import its agent, stand in for its model and memory."""

    def make(preset: dict[str, Any], steps: list[Any]) -> tuple[Any, Any, Any]:
        made(tmp_path, **preset)
        monkeypatch.syspath_prepend(str(tmp_path / "my-agent" / "src"))
        for name in [m for m in sys.modules if m.startswith("my_agent")]:
            monkeypatch.delitem(sys.modules, name)
        memory_module = importlib.import_module("my_agent.memory")
        agent_module = importlib.import_module("my_agent.agent")
        client, recorded = async_memory(answer, fail_open=True)
        monkeypatch.setattr(memory_module, "_memory", lambda: client)
        monkeypatch.setattr(agent_module.agent, "model", ScriptedModel(steps))
        monkeypatch.setenv("OPENAI_AGENTS_DISABLE_TRACING", "1")
        return agent_module, memory_module.MemoryContext("dana"), recorded

    return make


@pytest.mark.anyio
async def test_the_created_agent_recalls_searches_and_remembers(created: Any) -> None:
    search = [function_call("memory_search", {"query": "home"}, call_id="c1")]
    agent, context, recorded = created({}, [search, [assistant_message("Lisbon.")]])
    result = await agent.reply("Where do I live?", context)
    assert result.final_output == "Lisbon."
    assert routes(recorded) == ["search", "search", "add"]  # recall, the tool, remember


@pytest.mark.anyio
async def test_the_nodes_only_agent(created: Any) -> None:
    agent, context, recorded = created({"parts": ("nodes",)}, [[assistant_message("Lisbon.")]])
    await agent.reply("Where do I live?", context)
    assert routes(recorded) == ["search", "add"]


@pytest.mark.anyio
async def test_the_tools_only_agent_lets_the_model_save(created: Any) -> None:
    save = [function_call("memory_add", {"text": "Lives in Lisbon."}, call_id="c1")]
    agent, context, recorded = created({"parts": ("tools",)}, [save, [assistant_message("Ok.")]])
    await agent.reply("I live in Lisbon.", context)
    assert routes(recorded) == ["add"]
    assert json.loads(recorded.last.content)["items"][0]["text"] == "Lives in Lisbon."
