def test_doctor_checks_the_sdk_for_its_memory_file(tmp_path: Path) -> None:
    deps = '"openai-agents>=0.24", "twinmemory>=0.2"'
    (tmp_path / "pyproject.toml").write_text(f'[project]\nname = "a"\ndependencies = [{deps}]\n')
    site = tmp_path / ".venv" / "lib" / "python3.12" / "site-packages"
    for dist in ("openai_agents-0.2.0", "twinmemory-0.2.0"):
        (site / f"{dist}.dist-info").mkdir(parents=True)
    values = {"version": "0.2.0", "fast": "False"}
    (tmp_path / "memory.py").write_text(render("openai_agents/memory.py.tmpl", ["nodes"], values))
    (tmp_path / ".env").write_text(f"{env.KEY}=tm_x\n")
    (tmp_path / ".gitignore").write_text(".env\n")
    console = quiet()

    assert doctor(tmp_path, console) == 1

    text = said(console)
    assert "✓ dependencies: twinmemory, openai-agents" in text and "langgraph" not in text
    assert "✗ openai-agents 0.2.0 is older than 0.3" in text


