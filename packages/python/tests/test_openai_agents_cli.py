def made(tmp_path: Path, model: str = "", **options: Any) -> tuple[int, Any, Recorder]:
    recorder = Recorder()
    options.setdefault("skip_key", True)
    console = quiet()
    told = Options(framework="openai-agents", run=recorder, **options)
    return create("my-agent", tmp_path, model, told, console), console, recorder


def test_create_makes_a_runnable_project(tmp_path: Path) -> None:
    code, console, recorder = made(tmp_path)

    assert code == 0
    root = tmp_path / "my-agent"
    for path in ("pyproject.toml", "README.md", ".gitignore", ".env", ".env.example"):
        assert (root / path).exists(), path
    assert not (root / "langgraph.json").exists()
    for path in ("__init__.py", "agent.py", "chat.py", "memory.py"):
        assert (root / "src" / "my_agent" / path).exists(), path
    assert env.read(root / ".env") == {"MODEL": "", "OPENAI_API_KEY": "", env.KEY: ""}
    assert recorder.ran == [["uv", "add", "twinmemory>=0.2", "openai-agents>=0.3", "python-dotenv"]]
    text = said(console)
    assert "fill in OPENAI_API_KEY and TWIN_MEMORY_API_KEY in .env" in text
    assert "uv run python -m my_agent.chat --user dana" in text and "langgraph" not in text


def test_create_with_a_model(tmp_path: Path) -> None:
    made(tmp_path, model="gpt-5-mini")
    assert env.read(tmp_path / "my-agent" / ".env")["MODEL"] == "gpt-5-mini"


def test_create_dry_run_makes_nothing(tmp_path: Path) -> None:
    code, console, recorder = made(tmp_path, dry_run=True)
    assert code == 0 and recorder.ran == [] and list(tmp_path.iterdir()) == []
    assert "would    write src/my_agent/agent.py" in said(console)
    assert "langgraph" not in said(console)


