"""`twinmemory doctor`: whether a project is set up for memory, one line per check, each with
how to fix it when it is not. Reads everything and changes nothing; the one request it makes
is the key's check, which is free.
"""

from __future__ import annotations

import re
from pathlib import Path

from twinmemory._cli import env, project
from twinmemory._cli.scaffold import MINIMUMS
from twinmemory._cli.ui import Console
from twinmemory._version import __version__

_GENERATED = re.compile(r"Generated by `twinmemory init langgraph[^`]*` \(twinmemory ([^)]+)\)")


def doctor(cwd: Path, console: Console) -> int:
    """0 when every check passes, 1 when any fails."""
    root = project.find_root(cwd)
    if root is None:
        console.fail("no Python project here; run it from your project.")
        return 1
    console.line(f"twinmemory {__version__} - checking {root}")
    written = _written(root, console)
    results = [bool(written), _dependencies(root, console), _versions(root, console)]
    results.append(_key(root, console, writes=any(_saves(path) for path in written)))
    console.line()
    console.line("All good." if all(results) else "Fix what is marked ✗, then run doctor again.")
    return 0 if all(results) else 1


def _mark(console: Console, ok: bool | None, what: str, fix: str = "") -> bool:
    sign = {True: "✓", False: "✗", None: "-"}[ok]
    console.line(f"  {sign} {what}")
    if ok is False and fix:
        console.line(f"      {fix}")
    return ok is not False


def _written(root: Path, console: Console) -> list[Path]:
    """The memory files `init` wrote here, each marked; none is a failure."""
    found = [
        (path, match.group(1))
        for path in project.sources(root)
        if (match := _GENERATED.search(path.read_text(errors="ignore")[:2000]))
    ]
    if not found:
        _mark(console, False, "no memory file", "run `twinmemory init langgraph`")
    for path, version in found:
        _mark(console, True, f"memory file {path.relative_to(root)} (written by {version})")
    return [path for path, _ in found]


def _saves(path: Path) -> bool:
    """Whether a memory file writes to memory: `remember`, or the `memory_add` tool."""
    text = path.read_text(errors="ignore")
    return "def remember(" in text or "def memory_add(" in text


def _dependencies(root: Path, console: Console) -> bool:
    missing = [p for p in MINIMUMS if not project.declares(root, p)]
    if missing:
        add = " ".join(f"'{p}>={MINIMUMS[p]}'" for p in missing)
        tool = project.installer(root, missing).name
        return _mark(console, False, f"not dependencies: {', '.join(missing)}", f"{tool} add {add}")
    return _mark(console, True, f"dependencies: {', '.join(MINIMUMS)}")


def _versions(root: Path, console: Console) -> bool:
    site = project.environment(root)
    if site is None:
        return _mark(console, None, "installed versions not checked: no .venv in the project")
    ok = True
    for package, minimum in MINIMUMS.items():
        version = project.installed(site, package)
        if version is None:
            ok = (
                _mark(
                    console,
                    False,
                    f"{package} is not installed",
                    "install the project's dependencies",
                )
                and ok
            )
        elif project.older(version, minimum):
            ok = (
                _mark(
                    console,
                    False,
                    f"{package} {version} is older than {minimum}",
                    f"upgrade it to >={minimum}",
                )
                and ok
            )
        else:
            _mark(console, True, f"{package} {version}")
    return ok


def _key(root: Path, console: Console, *, writes: bool) -> bool:
    key, base_url = env.resolve(root)
    where = base_url or "the hosted service"
    if not key:
        fix = f"put a key in .env as {env.KEY}= (console, under API keys)"
        return _mark(console, False, f"no {env.KEY}", fix)
    kept_out = env.ignored(root) or _mark(
        console, False, ".env is not in .gitignore", "add .env to .gitignore"
    )
    checked = env.check(key, base_url)
    if not checked.ok:
        fix = f"check {env.KEY} and {env.BASE_URL}"
        return _mark(console, False, f"key at {where}: {checked.detail}", fix)
    if writes and checked.writes is False:
        fix = "use a key that writes (console, under API keys)"
        why = f"key at {where} only reads, and the memory file saves: remember and"
        return _mark(console, False, f"{why} memory_add will be refused", fix)
    return _mark(console, True, f"key at {where}: {checked.detail}") and kept_out
