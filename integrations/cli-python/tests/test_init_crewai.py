"""`alexein-cli init crewai`: classic and JSON crews, what it refuses, the CrewAI version it
needs, and the lines it prints."""

from __future__ import annotations

from pathlib import Path

import pytest
from test_cli import Project, quiet, said
from test_crewai_project import classic, json_crew

from alexein_cli import main


@pytest.fixture
def project(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Project:
    from alexein_cli import env

    monkeypatch.delenv(env.KEY, raising=False)
    monkeypatch.delenv(env.BASE_URL, raising=False)
    return Project(tmp_path, monkeypatch)


def crewai_project(p: Project, kind: str = "classic") -> Path:
    if kind == "classic":
        home = classic(p.root, "my_crew")
    else:
        json_crew(p.root)
        home = p.root
    (p.root / "uv.lock").write_text("")
    return home


def test_a_classic_crew_gets_memory_py_beside_crew_py(project: Project) -> None:
    crewai_project(project)
    code, console = project.init(framework="crewai")
    assert code == 0
    written = project.text("src/my_crew/memory.py")
    assert "alexein_memory = AlexeinMemory(" in written and "def whose(" in written
    assert "Generated by `alexein-cli init crewai`" in written
    text = said(console)
    assert "wrote    ./src/my_crew/memory.py" in text
    assert "from my_crew.memory import alexein_memory, whose" in text
    assert "memory = alexein_memory" in text and "@before_kickoff" in text
    assert "alexein_memory.tools(user_id)" in text and "save_result(" in text
    assert 'kickoff(inputs={"user_id": "dana"' in text


def test_a_json_crew_gets_memory_py_beside_its_definition(project: Project) -> None:
    crewai_project(project, "json")
    code, console = project.init(framework="crewai")
    assert code == 0 and (project.root / "memory.py").exists()
    text = said(console)
    assert '"memory": {"python": "memory.alexein_memory"}' in text
    assert '"before_kickoff_callbacks": [{"python": "memory.whose"}]' in text
    assert 'crew, _ = load_crew("crew.jsonc")' in text
    assert 'crew.kickoff(inputs={"user_id": "dana"' in text
    assert "MyCrew" not in text  # a JSON crew has no class


def test_a_flow_is_refused(project: Project) -> None:
    (project.root / "pyproject.toml").write_text(
        '[project]\nname = "f"\n\n[tool.crewai]\ntype = "flow"\n'
    )
    code, console = project.init(framework="crewai")
    assert code == 1 and "Flows are not supported" in said(console)
    assert not (project.root / "memory.py").exists()


def test_a_project_without_crewai_is_refused_even_with_yes(project: Project) -> None:
    project.uv()
    code, console = project.init(framework="crewai", console=quiet(yes=True))
    assert code == 1
    assert "not a CrewAI crew" in said(console)
    assert "alexein-cli create crewai <name>" in said(console)
    assert project.ran == []


def test_an_old_crewai_stops_with_the_upgrade(project: Project) -> None:
    crewai_project(project)
    project.installed(crewai="1.14.6")
    code, console = project.init(framework="crewai")
    assert code == 1
    assert "crewai 1.14.6 (needs >=1.15)" in said(console)
    assert "uv add 'crewai>=1.15'" in said(console)
    assert not (project.root / "src/my_crew/memory.py").exists()


def test_a_newer_crewai_warns(project: Project) -> None:
    crewai_project(project)
    project.installed(crewai="1.17.0")
    code, console = project.init(framework="crewai")
    assert code == 0
    assert "warning  crewai 1.17.0 is newer than this release was tested with (1.15)" in said(
        console
    )


def test_the_tested_crewai_says_nothing(project: Project) -> None:
    crewai_project(project)
    project.installed(crewai="1.15.28")
    _, console = project.init(framework="crewai")
    assert "newer than" not in said(console)


def test_crewai_installs_the_client_with_its_extra(project: Project) -> None:
    crewai_project(project)
    project.init(framework="crewai")
    assert project.ran == [["uv", "add", "alexein[crewai]>=0.3"]]


def test_graph_is_refused_for_crewai(project: Project) -> None:
    crewai_project(project)
    code, console = project.init(framework="crewai", graph="x")
    assert code == 2 and "--graph is for langgraph" in said(console)
    assert not (project.root / "src/my_crew/memory.py").exists()


def test_dry_run_and_key_setup_work_as_for_langgraph(project: Project) -> None:
    crewai_project(project)
    code, console = project.init(framework="crewai", dry_run=True, key="tm_k")
    assert code == 0 and "would    write ./src/my_crew/memory.py" in said(console)
    assert project.ran == [] and not (project.root / ".env").exists()
    project.check = project.check.__class__(True, False, "o/p, reads only")
    _, console = project.init(framework="crewai", key="tm_read")
    assert "this key only reads: saving what a task learned" in said(console)


def test_the_command_line_takes_crewai(project: Project, monkeypatch: pytest.MonkeyPatch) -> None:
    crewai_project(project)
    monkeypatch.chdir(project.root)
    assert main(["init", "crewai", "--no-install", "--yes", "--fast"], quiet()) == 0
    assert "FAST = True" in project.text("src/my_crew/memory.py")


def test_an_unknown_framework_names_both(project: Project) -> None:
    code, console = project.init(framework="autogen")
    assert code == 2 and "langgraph" in said(console) and "crewai" in said(console)


def test_a_newer_crewai_says_what_to_watch_for(project: Project) -> None:
    crewai_project(project)
    project.installed(crewai="1.17.0")
    _, console = project.init(framework="crewai")
    assert "warnings on the `alexein` logger" in said(console)


def test_crewai_not_found_says_its_version_was_not_checked(project: Project) -> None:
    crewai_project(project)
    code, console = project.init(framework="crewai")
    assert code == 0 and "crewai version not checked" in said(console)
