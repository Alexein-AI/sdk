def lint_clean(path: Path) -> None:
    """Code that lands in projects with linters of their own must pass them as written, at
    black's and ruff's default line length of 88, with nothing unused."""
    rules = "E,F,I,B,UP,SIM,RUF,W"
    lint = [sys.executable, "-m", "ruff", "check", "--isolated", "--select", rules, str(path)]
    fmt = [sys.executable, "-m", "ruff", "format", "--isolated", "--check", str(path)]
    for command in (lint, fmt):
        done = subprocess.run(command, cwd=path.parent, capture_output=True, text=True, check=False)
        assert done.returncode == 0, done.stdout + done.stderr


@pytest.mark.parametrize("framework", ["langgraph", "openai-agents", "crewai"])
@pytest.mark.parametrize("fast", [False, True])
def test_every_file_is_clean_and_short(tmp_path: Path, framework: str, fast: bool) -> None:
    """The file is the settings and the wiring: everything else is the client's."""
    written = write(tmp_path, Options(framework=framework, fast=fast))
    lint_clean(written)
    text = written.read_text()
    code = [line for line in text.split('"""', 2)[2].splitlines() if line.strip()]
    assert len(text.splitlines()) <= 75 and len(code) <= 30, (len(text.splitlines()), len(code))
    assert f"FAST = {fast}" in text
    for setting in ("STRICT = False", "MAX_CHARS = 4000", "TIMEOUT = 10.0"):
        assert setting in text
    assert "fast=FAST,\n    max_chars=MAX_CHARS,\n    strict=STRICT,\n    timeout=TIMEOUT," in text


def test_the_file_imports_no_framework_of_its_own(tmp_path: Path) -> None:
    for framework in ("langgraph", "openai-agents", "crewai"):
        text = write(tmp_path / framework, Options(framework=framework)).read_text()
        code = text.split('"""', 2)[2].splitlines()
        imported = [line for line in code if line.startswith(("from ", "import "))]
        assert imported and all(
            line.startswith(("from alexein.", "from typing ")) for line in imported
        ), imported


