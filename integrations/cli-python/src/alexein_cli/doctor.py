"""`alexein-cli doctor`: whether a project is set up for memory, one line per check, each with
how to fix it when it is not. Reads everything and changes nothing; the one request it makes
is the key's check, `memory.me()`, which is free.
"""

from __future__ import annotations

import re
import subprocess
from pathlib import Path

from alexein_cli import crews, env, project
from alexein_cli._version import __version__
from alexein_cli.scaffold import CLIENT, EXTRAS, MINIMUMS, MODULES, NAMES, requirement
from alexein_cli.ui import Console

_GENERATED = re.compile(r"Generated by `alexein-cli init ([a-z-]+)[^`]*` \(alexein-cli ([^)]+)\)")


def doctor(cwd: Path, console: Console) -> int:
    """0 when every check passes, 1 when any fails."""
    root = project.find_root(cwd)
    if root is None:
        console.fail("no Python project here; run it from your project.")
        return 1
    console.line(f"alexein-cli {__version__} - checking {root}")
    found = project.crew(root)
    if found is not None and found.kind == "flow":
        console.fail("this is a CrewAI Flow; Flows are not supported yet.")
        return 1
    used = (f for f in ("langgraph", "openai-agents") if project.uses(root, f))
    framework = "crewai" if found is not None else next(used, "langgraph")
    written = _written(root, framework, console)
    frameworks = sorted({f for _, f in written} or {framework})
    minimums = _minimums_for(frameworks)
    results = [bool(written), _dependencies(root, frameworks, console)]
    results.append(_versions(root, minimums, console))
    results.append(_importable(root, frameworks, console))
    results.append(_key(root, console))
    console.line()
    console.line("All good." if all(results) else "Fix what is marked ✗, then run doctor again.")
    return 0 if all(results) else 1


def _mark(console: Console, ok: bool | None, what: str, fix: str = "") -> bool:
    sign = {True: "✓", False: "✗", None: "-"}[ok]
    console.line(f"  {sign} {what}")
    if ok is False and fix:
        console.line(f"      {fix}")
    return ok is not False


def _written(root: Path, framework: str, console: Console) -> list[tuple[Path, str]]:
    """The memory files `init` wrote here, each marked with what it is for; none is a failure."""
    found = [
        (path, match.group(1), match.group(2))
        for path in project.sources(root)
        if (match := _GENERATED.search(path.read_text(errors="ignore")[:2000]))
    ]
    if not found:
        _mark(console, False, "no memory file", f"run `alexein-cli init {framework}`")
    found = [(path, kind, version) for path, kind, version in found if kind in MINIMUMS]
    for path, kind, version in found:
        where = path.relative_to(root)
        _mark(console, True, f"memory file {where} (written by {version}, for {NAMES[kind]})")
    return [(path, kind) for path, kind, _ in found]


def _minimums_for(frameworks: list[str]) -> dict[str, str]:
    """What the memory files here need installed: each framework's, together, and CrewAI
    itself for a crew's."""
    needed = {p: v for f in frameworks for p, v in MINIMUMS[f].items()}
    if "crewai" in frameworks:
        needed["crewai"] = crews.CREWAI_MINIMUM
    return needed


def _dependencies(root: Path, frameworks: list[str], console: Console) -> bool:
    """The client is a dependency, with each framework's extra."""
    wanted = [requirement(f) for f in frameworks]
    missing = [
        named
        for named, f in zip(wanted, frameworks, strict=True)
        if not project.declares(root, CLIENT, EXTRAS[f])
    ]
    if missing:
        fix = project.installer(root, missing).hint
        return _mark(console, False, f"not dependencies: {', '.join(missing)}", fix)
    return _mark(console, True, f"dependencies: {', '.join(wanted)}")


def _versions(root: Path, minimums: dict[str, str], console: Console) -> bool:
    site = project.environment(root)
    if site is None:
        return _mark(console, None, "installed versions not checked: no .venv in the project")
    ok = True
    for package, minimum in minimums.items():
        version = project.installed(site, package)
        if version is None:
            fix = "install the project's dependencies"
            ok = _mark(console, False, f"{package} is not installed", fix) and ok
        elif project.older(version, minimum):
            fix = f"upgrade it to >={minimum}"
            ok = _mark(console, False, f"{package} {version} is older than {minimum}", fix) and ok
        elif package == "crewai" and crews.newer_than_tested(version):
            tested = crews.CREWAI_TESTED
            _mark(
                console,
                None,
                f"crewai {version} is newer than this release was tested with ({tested}); "
                "it should work - if tasks stop recalling or saving memory, "
                "look for warnings on the `alexein` logger",
            )
        else:
            _mark(console, True, f"{package} {version}")
    return ok


def _importable(root: Path, frameworks: list[str], console: Console) -> bool:
    """Each integration module imports in the project's own Python: the client is there, and
    so is everything its extra brings. Run there, not here: this CLI never imports a
    framework."""
    python = project.interpreter(root)
    if python is None:
        return _mark(console, None, "imports not checked: no .venv in the project")
    ok = True
    for framework in frameworks:
        module = MODULES[framework]
        try:
            done = subprocess.run(
                [str(python), "-c", f"import {module}"],
                cwd=root,
                capture_output=True,
                text=True,
                timeout=120,
                check=False,
            )
        except (OSError, subprocess.TimeoutExpired) as error:
            ok = _mark(console, False, f"{module} could not be checked: {error}") and ok
            continue
        if done.returncode == 0:
            _mark(console, True, f"{module} imports")
            continue
        last = (done.stderr.strip().splitlines() or ["it failed"])[-1]
        fix = project.installer(root, [requirement(framework)]).hint
        ok = _mark(console, False, f"{module} does not import: {last}", fix) and ok
    return ok


def _key(root: Path, console: Console) -> bool:
    key, base_url = env.resolve(root)
    if not key:
        fix = f"put a key in .env as {env.KEY}= (console, under API keys)"
        return _mark(console, False, f"no {env.KEY}", fix)
    _mark(console, True, f"{env.KEY} from {env.origin(root, env.KEY)}")
    if base_url:
        _mark(console, True, f"{env.BASE_URL} from {env.origin(root, env.BASE_URL)}: {base_url}")
    for name in (env.KEY, env.BASE_URL):
        if env.differs(root, name):
            _mark(
                console,
                None,
                f"{name} is set in .env and in the environment, differently; this check uses "
                ".env's, and load_dotenv() keeps the environment's",
            )
    where = env.address(base_url)  # the client's, so it is where the check goes
    kept_out = env.ignored(root) or _mark(
        console, False, ".env is not in .gitignore", "add .env to .gitignore"
    )
    checked = env.check(key, base_url)
    if not checked.ok:
        fix = f"check {env.KEY} and {env.BASE_URL}"
        return _mark(console, False, f"key at {where}: {checked.detail}", fix)
    _mark(console, True, f"key at {where}: {checked.detail}")
    if checked.writes is False:
        _mark(
            console,
            None,
            "the key only reads: remember, memory_add and saving what a crew learned "
            "need one that writes",
        )
    return kept_out
